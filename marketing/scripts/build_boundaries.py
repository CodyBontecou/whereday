#!/usr/bin/env python3
"""Rebuild marketing/public/assets/visited-countries-data.mjs from Natural Earth.

Not part of build_site.py: the asset is committed, so a normal site build needs
no network. Run this only to change the boundary set:

    python3 marketing/scripts/build_boundaries.py [path/to/ne_50m_admin_0_countries.geojson]

Without an argument it downloads Natural Earth 1:50m Admin 0 – Countries,
version 5.1.2, from the natural-earth-vector repository's v5.1.2 tag. Natural
Earth is public domain: https://www.naturalearthdata.com/about/terms-of-use/

Output: coordinates rounded to 0.01 degree, rings simplified with
Douglas-Peucker (tolerance TOLERANCE degrees), stored as delta-encoded integers.
"""
import json, sys, urllib.request
from pathlib import Path

VERSION = "5.1.2"
URL = f"https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v{VERSION}/geojson/ne_50m_admin_0_countries.geojson"
OUT = Path(__file__).resolve().parents[1] / "public/assets/visited-countries-data.mjs"
SCALE = 100          # integer units per degree
TOLERANCE = 0.01     # degrees
MIN_RING_SPAN = 0.03 # drop rings smaller than this (degrees) unless needed


def simplify(ring, tol):
    """Douglas-Peucker on an open point list; endpoints are kept."""
    keep = [False] * len(ring)
    keep[0] = keep[-1] = True
    stack = [(0, len(ring) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = ring[a]; bx, by = ring[b]
        dx, dy = bx - ax, by - ay
        length = dx * dx + dy * dy
        best, at = -1.0, -1
        for i in range(a + 1, b):
            px, py = ring[i]
            if length == 0:
                d = (px - ax) ** 2 + (py - ay) ** 2
            else:
                t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / length))
                d = (px - ax - t * dx) ** 2 + (py - ay - t * dy) ** 2
            if d > best:
                best, at = d, i
        if best > tol * tol:
            keep[at] = True
            stack.append((a, at)); stack.append((at, b))
    return [p for p, k in zip(ring, keep) if k]


def prepare(ring, tol):
    pts = []
    for lon, lat in ring[:-1]:
        p = (round(lon * SCALE), round(lat * SCALE))
        if not pts or pts[-1] != p:
            pts.append(p)
    if len(pts) > 1 and pts[0] == pts[-1]:
        pts.pop()
    if len(pts) < 3:
        return None
    out = simplify(pts + [pts[0]], tol * SCALE)[:-1]
    return out if len(out) >= 3 else None


def area(ring):
    return abs(sum(ring[i][0] * ring[(i + 1) % len(ring)][1] - ring[(i + 1) % len(ring)][0] * ring[i][1] for i in range(len(ring)))) / 2


def delta(ring):
    flat, px, py = [], 0, 0
    for x, y in ring:
        flat += [x - px, y - py]; px, py = x, y
    return flat


def main():
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text())
    else:
        data = json.load(urllib.request.urlopen(URL, timeout=120))
    groups = {}
    for f in data["features"]:
        p = f["properties"]
        code = p["ISO_A2_EH"] if p["ISO_A2_EH"] != "-99" else p["ADM0_A3"]
        geom = f["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        g = groups.setdefault(code, {"name": p["NAME"], "area": 0.0, "polys": []})
        for poly in polys:
            outer_area = area([tuple(c) for c in poly[0]])
            if outer_area > g["area"] and not g["polys"] or outer_area > g["area"]:
                g["area"] = outer_area; g["name"] = p["NAME"]
            g["polys"].append(poly)
    countries = []
    for code in sorted(groups):
        g = groups[code]
        polys = []
        for poly in g["polys"]:
            rings = []
            for i, ring in enumerate(poly):
                r = prepare(ring, TOLERANCE)
                if r is None: continue
                xs = [x for x, _ in r]; ys = [y for _, y in r]
                if i == 0 and max(max(xs) - min(xs), max(ys) - min(ys)) < MIN_RING_SPAN * SCALE: continue
                if i > 0 and area(r) < (0.05 * SCALE) ** 2: continue
                rings.append(r)
            if rings:
                polys.append(rings)
        if not polys:  # keep the largest ring so tiny countries never vanish
            biggest = max((poly[0] for poly in g["polys"]), key=lambda r: area([tuple(c) for c in r]))
            r = prepare(biggest, TOLERANCE / 4)
            polys.append([r])
        countries.append([code, g["name"], [[delta(r) for r in rings] for rings in polys]])
    body = json.dumps(countries, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// Generated by marketing/scripts/build_boundaries.py. Do not edit by hand.\n"
        f"// Natural Earth 1:50m Admin 0 - Countries, version {VERSION} (public domain, https://www.naturalearthdata.com/about/terms-of-use/).\n"
        f"// Coordinates are integers in 1/{SCALE} degree, delta-encoded (x, y pairs per ring), simplified to {TOLERANCE} degree.\n"
        f"export const BOUNDARY_VERSION = {json.dumps(VERSION)};\n"
        f"export const BOUNDARY_SCALE = {SCALE};\n"
        f"export const BOUNDARY_DATA = {body};\n")
    print(OUT, OUT.stat().st_size, len(countries), "countries")


main()
