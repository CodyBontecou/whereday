#!/usr/bin/env python3
"""Freeze actual Foundation region membership and actual Swift country-day outputs; verify generated Kotlin."""
from pathlib import Path
import argparse
import hashlib
import json
import platform
import re
import subprocess
import tempfile

ROOT=Path(__file__).resolve().parents[2]
SOURCES=[ROOT/p for p in ['IsoMe/Models/CountryStay.swift','IsoMe/Models/Visit.swift','IsoMe/Models/LocationPoint.swift','IsoMe/Views/CountryDaysView.swift','android/scripts/fixtures/CountryRegions.swift','android/scripts/generate_country_regions.py']]
OUTPUT=ROOT/'android/domain/src/test/resources/ios-country-regions.json'
KOTLIN=ROOT/'android/domain/src/main/kotlin/com/bontecou/whereday/domain/CountryRegions.kt'

def picker_helper(text):
    start=text.index('static func matchingCountries(')
    end=text.index('{',start)+1;depth=1
    while depth:
        depth+=(text[end]=='{')-(text[end]=='}');end+=1
    return text[start:end]

def picker_bodies(text):
    starts=list(re.finditer(r'private\s+var\s+countries:\s*\[\(code:\s*String,\s*name:\s*String\)\]\s*\{',text))
    if len(starts)!=2:raise ValueError('Review changed country eligibility/selection declarations')
    result=[]
    for match in starts:
        start=match.end();end=start;depth=1
        while depth:
            depth+=(text[end]=='{')-(text[end]=='}');end+=1
        result.append(text[start:end-1].strip())
    return result

def fingerprints(frozen):
    result={str(p.relative_to(ROOT)):hashlib.sha256(data).hexdigest() for p,data in frozen.items() if p!=SOURCES[3]}
    for name,body in zip(['CountryStayEditor.countries','CountrySelectionView.countries'],picker_bodies(frozen[SOURCES[3]].decode())):
        result[str(SOURCES[3].relative_to(ROOT))+'#'+name]=hashlib.sha256(body.encode()).hexdigest()
    result[str(SOURCES[3].relative_to(ROOT))+'#CountrySelectionView.matchingCountries']=hashlib.sha256(picker_helper(frozen[SOURCES[3]].decode()).encode()).hexdigest()
    return result

def provenance():
    return fingerprints({p:p.read_bytes() for p in SOURCES})

def kotlin(snapshot):
    all_codes=snapshot['all'];picker=snapshot['picker'];names=snapshot['names']
    assert all_codes==sorted(set(all_codes)) and picker==sorted(set(picker))
    assert all(re.fullmatch('[A-Z]{2}|[0-9]{3}',c) for c in all_codes)
    assert picker==[c for c in all_codes if len(c)==2] and 'ZZ' not in all_codes
    def quoted(s):return json.dumps(s,ensure_ascii=False).replace('$','\\$')
    lines=['// Generated by scripts/generate_country_regions.py; review/regenerate the Swift snapshot, not this file.',
           'package com.bontecou.whereday.domain','','import java.util.Collections','import java.util.Locale','',
           '/** Region membership follows the frozen Foundation reference, independently of Android ICU version. */',
           'object CountryRegions {','    val all:Set<String> = Collections.unmodifiableSet(setOf(']
    lines += ['        '+','.join(quoted(c) for c in group)+',' for group in [all_codes[i:i+15] for i in range(0,len(all_codes),15)]]
    lines += ['    ))','    val picker:Set<String> = Collections.unmodifiableSet(all.filter {it.length==2}.toSet())',
              '    fun normalize(raw:String?):String? = raw?.uppercase(Locale.ROOT)?.takeIf {it in all}',
              '    fun displayName(code:String,locale:Locale):String {',
              '        val native=Locale.Builder().setRegion(code).build().getDisplayCountry(locale)',
              '        if(native.isNotBlank() && native!=code) return native',
              '        return fallbackName(code,locale.language)', '    }',
              '    fun fallbackName(code:String,language:String):String = (if(language=="es") spanish else english)[code] ?: code']
    for language,var in [('en','english'),('es','spanish')]:
        assert set(names[language])==set(picker)
        lines += ['    private val '+var+'=mapOf(']+['        '+quoted(c)+' to '+quoted(names[language][c])+',' for c in picker]+['    )']
    return '\n'.join(lines+['}',''])

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-source',action='store_true')
    parser.add_argument('--check-generated',action='store_true')
    args=parser.parse_args()
    if args.check_source or args.check_generated:
        snapshot=json.loads(OUTPUT.read_text())
        if snapshot['provenance']!=provenance():raise SystemExit('Country-region reference source changed; review and regenerate on macOS')
        if KOTLIN.read_text()!=kotlin(snapshot):raise SystemExit('Generated country-region Kotlin differs from the reviewed reference')
        print('PASS: country-region source hashes and generated Kotlin match')
    else:
        if platform.system()!='Darwin':raise SystemExit('Generate actual SwiftData/Foundation references on macOS')
        frozen={p:p.read_bytes() for p in SOURCES}
        captured=fingerprints(frozen)
        model=frozen[SOURCES[0]].decode();view=frozen[SOURCES[3]].decode()
        expression=re.search(r'private static let countryCodes = (.+)',model).group(1)
        eligible,picker=picker_bodies(view)
        harness=frozen[SOURCES[4]].decode().replace('__COUNTRY_CODES__',expression).replace('__PICKER_BODY__',picker).replace('__ELIGIBLE_BODY__',eligible).replace('__PICKER_HELPERS__',picker_helper(view))
        with tempfile.TemporaryDirectory(prefix='whereday-country-regions-') as directory:
            folder=Path(directory);fixture=folder/'Fixture.swift';fixture.write_text(harness);binary=folder/'fixture'
            models=[]
            for source in SOURCES[:3]:
                copy=folder/source.name;copy.write_bytes(frozen[source]);models.append(copy)
            arch='arm64' if platform.machine()=='arm64' else 'x86_64'
            subprocess.run(['swiftc','-parse-as-library','-target',f'{arch}-apple-macosx14.0','-module-cache-path',str(folder/'modules'),*map(str,models),str(fixture),'-o',str(binary)],check=True)
            snapshot=json.loads(subprocess.run([str(binary)],check=True,capture_output=True,text=True).stdout)
        if provenance()!=captured:raise SystemExit('Reference sources changed during generation; rerun after reviewing the source changes')
        snapshot['provenance']=captured
        snapshot['pickerSourceContextSHA256']=hashlib.sha256(frozen[SOURCES[3]]).hexdigest()
        text=kotlin(snapshot)
        OUTPUT.write_text(json.dumps(snapshot,ensure_ascii=False,indent=2)+'\n');KOTLIN.write_text(text)
        print(f"Generated {len(snapshot['all'])} regions, {len(snapshot['picker'])} picker regions and {len(snapshot['cases'])} actual Swift calculator cases")

if __name__=="__main__":
    main()
