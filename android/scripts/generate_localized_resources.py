#!/usr/bin/env python3
"""Generate explicitly mapped Android resources; never guess Swift format/plural conversions."""
import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANDROID = ROOT / "android"
RES = ANDROID / "app/src/main/res"
RESOURCE_ROOTS = {"app": RES, "platform": ANDROID / "platform/src/main/res"}
CATALOG = ROOT / "IsoMe/Localizable.xcstrings"


def signature(text):
    text = text.replace("%%", "")
    tokens = re.findall(r"%(?:(\d+)\$)?([ds])", text)
    if "%" in re.sub(r"%(?:(\d+)\$)?([ds])", "", text):
        raise ValueError("Unsupported format token; review and map it explicitly")
    return sorted((int(index) if index else i + 1, kind) for i, (index, kind) in enumerate(tokens))


def validate(source, translated):
    if isinstance(source, dict):
        if not isinstance(translated, dict) or set(source) != set(translated):
            raise ValueError("Plural quantities must be mapped explicitly")
        for quantity in source:
            validate(source[quantity], translated[quantity])
    elif not isinstance(translated, str) or not translated.strip() or signature(source) != signature(translated):
        raise ValueError("Missing text or changed placeholder identity/type")


def read_defaults(root):
    result = {}
    for path in sorted((root / "values").glob("*.xml")):
        for node in ET.parse(path).getroot():
            if node.tag not in ("string", "plurals") or node.get("translatable") == "false":
                continue
            name = node.attrib["name"]
            if name in result:
                raise ValueError(f"Duplicate default resource: {name}")
            if node.tag == "plurals":
                result[name] = {item.attrib["quantity"]: item.text or "" for item in node}
            else:
                if list(node):
                    raise ValueError(f"Styled resource needs explicit conversion: {name}")
                result[name] = node.text or ""
    return result


def module_defaults():
    return {module: read_defaults(root) for module, root in RESOURCE_ROOTS.items()}


def merge_defaults(modules):
    result = {}
    for module, values in modules.items():
        duplicates = set(result) & set(values)
        if duplicates:
            raise ValueError(f"Duplicate resource across modules: {sorted(duplicates)} in {module}")
        result.update(values)
    return result


def defaults():
    return merge_defaults(module_defaults())


def split_generated(text, modules):
    root = ET.fromstring(text)
    names = [node.attrib["name"] for node in root]
    owned = merge_defaults(modules)
    if len(names) != len(set(names)) or set(names) != set(owned):
        raise ValueError("Generated resource ownership mismatch")
    outputs = {}
    for module, source in modules.items():
        selected = ET.Element("resources")
        for node in root:
            if node.attrib["name"] in source:
                # Reparse so indentation of one output cannot modify another.
                selected.append(ET.fromstring(ET.tostring(node, encoding="unicode")))
        ET.indent(selected, space="    ")
        outputs[module] = "<!-- Generated by scripts/generate_localized_resources.py; edit localization inputs. -->\n" + ET.tostring(selected, encoding="unicode") + "\n"
    return outputs


def android_text(text):
    return text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')


def generate(source, pack, catalog):
    aliases = pack["catalog"]
    overrides = pack["translations"]
    if set(aliases) & set(overrides) or set(aliases) | set(overrides) != set(source):
        missing = sorted(set(source) - set(aliases) - set(overrides))
        extra = sorted((set(aliases) | set(overrides)) - set(source))
        raise ValueError(f"Translation coverage mismatch: missing={missing}, extra={extra}")
    translated = dict(overrides)
    for name, key in aliases.items():
        entry = catalog["strings"][key]
        english = entry.get("localizations", {}).get("en", {}).get("stringUnit", {}).get("value", key)
        unit = entry["localizations"][pack["locale"]]["stringUnit"]
        if english != source[name] or unit.get("state") != "translated":
            raise ValueError(f"Unreviewed or changed source mapping: {name}")
        # Catalog aliases in this first batch are static labels only. Swift placeholders/plurals
        # must be handled explicitly before they can become Android resources.
        if signature(english):
            raise ValueError(f"Formatted catalog entry needs explicit conversion: {name}")
        translated[name] = unit["value"]
    root = ET.Element("resources")
    for name in sorted(source):
        validate(source[name], translated[name])
        value = translated[name]
        if isinstance(value, dict):
            node = ET.SubElement(root, "plurals", name=name)
            for quantity, text in value.items():
                ET.SubElement(node, "item", quantity=quantity).text = android_text(text)
        else:
            ET.SubElement(root, "string", name=name).text = android_text(value)
    ET.indent(root, space="    ")
    return "<!-- Generated by scripts/generate_localized_resources.py; edit localization inputs. -->\n" + ET.tostring(root, encoding="unicode") + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    modules = module_defaults()
    source = merge_defaults(modules)
    catalog = json.loads(CATALOG.read_text())
    outputs = {}
    report = {"scope": "All currently externalized app/platform strings/plurals; hardcoded UI and other languages remain incomplete", "locales": {}}
    for path in sorted((ANDROID / "localization").glob("*.json")):
        if path.name == "coverage.json":
            continue
        pack = json.loads(path.read_text())
        if "locale" not in pack:
            raise ValueError(f"Missing locale: {path.name}")
        source_hash = hashlib.sha256(json.dumps(source, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
        if pack.get("defaultSourceSha256") != source_hash:
            raise ValueError(f"Default wording changed; review translations before updating {path.name}'s source hash")
        locale = pack["locale"]
        if not re.fullmatch(r"[a-z]{2}(?:-r[A-Z]{2})?", locale):
            raise ValueError("Map locale qualifiers explicitly before adding this locale")
        text = generate(source, pack, catalog)
        module_outputs = split_generated(text, modules)
        for module, generated in module_outputs.items():
            outputs[RESOURCE_ROOTS[module] / f"values-{locale}" / "generated.xml"] = generated
        selected_catalog = {key: catalog["strings"][key] for key in sorted(set(pack["catalog"].values()))}
        digest = lambda value: hashlib.sha256(value.encode()).hexdigest()
        report["locales"][locale] = {
            "resourceCount": len(source), "catalogAliases": len(pack["catalog"]),
            "defaultSha256": digest(json.dumps(source, ensure_ascii=False, sort_keys=True)),
            "inputSha256": digest(path.read_text()),
            "selectedCatalogSha256": digest(json.dumps(selected_catalog, ensure_ascii=False, sort_keys=True)),
            "outputSha256": digest(text),
            "modules": {module: {"resourceCount": len(modules[module]), "outputSha256": digest(generated)} for module, generated in module_outputs.items()},
        }
    outputs[ANDROID / "localization/coverage.json"] = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Stale localization output: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(f"Localization {'verified' if args.check else 'generated'}: {len(source)} resources, {len(report['locales'])} locale(s)")


if __name__ == "__main__":
    main()
